//! Calendar labels selected by the connection's locale.
//! Months run January through December; weekdays run Monday through Sunday.

pub(crate) struct CalendarLocale {
    pub(crate) name: &'static str,
    pub(crate) months: [&'static str; 12],
    pub(crate) days: [&'static str; 7],
    pub(crate) short_months: [&'static str; 12],
    pub(crate) short_days: [&'static str; 7],
}

thread_local! {
    static SESSION_LOCALE: std::cell::Cell<u8> = const { std::cell::Cell::new(0) };
}

fn resolve(value: &str) -> Option<u8> {
    if let Ok(index) = value.parse::<u8>() {
        return LOCALES.get(usize::from(index)).map(|_| index);
    }
    LOCALES
        .iter()
        .position(|locale| locale.name.eq_ignore_ascii_case(value))
        .and_then(|index| u8::try_from(index).ok())
}

/// Canonical calendar locale name for a name or numeric locale identifier.
#[must_use]
pub fn calendar_locale_name(value: &str) -> Option<&'static str> {
    resolve(value).map(|index| locale(usize::from(index)).name)
}

/// Installs the calendar locale for planning on this thread. `None` restores `en_US`.
/// An unknown locale leaves the current setting unchanged.
#[must_use]
pub fn set_session_calendar_locale(value: Option<&str>) -> bool {
    let Some(index) = value.map_or(Some(0), resolve) else {
        return false;
    };
    SESSION_LOCALE.set(index);
    true
}

/// The installed calendar locale, also used to separate cached query answers.
#[must_use]
pub fn session_calendar_locale() -> &'static str {
    locale(usize::from(session_locale_id())).name
}

pub(crate) fn session_locale_id() -> u8 {
    SESSION_LOCALE.get()
}

pub(crate) fn locale(index: usize) -> &'static CalendarLocale {
    LOCALES.get(index).unwrap_or(&LOCALES[0])
}

