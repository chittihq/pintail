//! One-to-one case mappings, generated from `MySQL`.
//!
//! Produced by asking a real `MySQL` 8 server for `UPPER` and `LOWER` of
//! every code point below U+20000 under one collation of each family, the
//! character followed by spaces so a mapping that needs more bytes than its
//! source still shows. Generated rather than transcribed: these are the
//! facts obtained as output.
//!
//! A character maps to exactly one character or to itself, never to a
//! sequence, and which mapping applies belongs to the collation's family:
//! the `0900` collations know more cased letters than `general_ci`,
//! `unicode_ci` and `utf8mb4_bin` do. ASCII is not listed; it maps as ASCII
//! does in every family.

/// Code points `first..=last`, every `step`-th one, each mapping to itself
/// plus `delta`.
pub(super) type CaseRun = (u32, u32, u32, i32);

